"""Generate a transactional, repeatable seed; never overwrite stock counts."""
import json
import random
import sys
from pathlib import Path

BACKEND = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(BACKEND))
from app.pharmacy.catalogue import load_catalogue


def literal(value):
    if value is None:
        return "NULL"
    if isinstance(value, dict):
        value = json.dumps(value, ensure_ascii=False)
    if isinstance(value, int):
        return str(value)
    return "'" + value.replace("'", "''") + "'"


def build_seed():
    medicines, brands = load_catalogue()
    rng = random.Random(41)
    for brand in brands:
        brand['stock_quantity'] = rng.choice([0, 0, 3, 8, 15, 24, 50, 75, 100, 150])
    statements = ["-- Generated by scripts/build_pharmacy_seed.py. Stock is preserved on rerun.", "begin;"]
    for table, rows, key in [("pharmacy_medicines", medicines, "id"), ("pharmacy_brands", brands, "brand_id")]:
        columns = list(rows[0])
        values = ",\n".join("(" + ",".join(literal(row[c]) for c in columns) + ")" for row in rows)
        updates = ",".join(f"{c}=excluded.{c}" for c in columns if c not in {key, 'stock_quantity'})
        statements.append(f"insert into public.{table} ({','.join(columns)}) values\n{values}\non conflict ({key}) do update set {updates};")
    statements.append("commit;\n")
    return "\n".join(statements), len(medicines), len(brands)


if __name__ == "__main__":
    sql, medicines, brands = build_seed()
    target = BACKEND / "database" / "phase_4_1_seed.sql"
    target.write_text(sql, encoding="utf-8")
    print(f"Generated {target.name}: {medicines} medicines, {brands} brands; random demo opening stock.")
